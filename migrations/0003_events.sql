-- Both the idempotency store and the outbox: a row is the accepted event, and
-- published_at IS NULL marks it as not yet handed to the broker.
CREATE TABLE events (
  event_id        uuid        PRIMARY KEY, -- UUIDv7, generated by the app
  tenant_id       uuid        NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  idempotency_key text        CHECK (char_length(idempotency_key) BETWEEN 1 AND 255),
  request_hash    text        NOT NULL,
  event_type      text        NOT NULL,
  payload         jsonb       NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  published_at    timestamptz,
  -- Serialises concurrent requests carrying the same key. Rows without a key
  -- never conflict because NULLs are distinct.
  UNIQUE (tenant_id, idempotency_key)
);

-- Keeps the relay's poll cheap: only rows still waiting to be published.
CREATE INDEX events_unpublished_idx
  ON events (created_at, event_id)
  WHERE published_at IS NULL;

